const LANGS=["fr","en","es","pt"];
let lang=localStorage.getItem("lang")||(navigator.language||"en").slice(0,2);
if(!LANGS.includes(lang))lang="en";
const t=k=>L[lang][k]??L.fr[k]??k;
function applyLang(){
  document.documentElement.lang=lang;
  document.querySelectorAll("[data-i18n]").forEach(e=>e.innerHTML=t(e.dataset.i18n));
  document.querySelectorAll(".lang button").forEach(b=>b.classList.toggle("on",b.dataset.l===lang));
  if(window.draw)draw();
}
document.addEventListener("DOMContentLoaded",()=>{
  document.querySelectorAll(".lang button").forEach(b=>b.onclick=()=>{lang=b.dataset.l;localStorage.setItem("lang",lang);applyLang();});
  applyLang();
});
